// @ts-nocheck -- this focused Node-side generator test is run by Vitest; the app does not ship Node typings.
// Generator for the factory kit level trims (`npm run kits:levels`). Each
// untrimmed factory kit plays its own groove through the real DR-1 worklet
// offline; KIT MIX's fit then moves the pad levels toward the PART · DRUMS
// curve, twice (LEARN, APPLY, LEARN, APPLY at the panel's default amount),
// so every kit lands on one tonal balance. The result is written for both
// the web (kitLevels.gen.ts) and the plugin (KitLevels.gen.h).
// KIT_LEVELS=write regenerates; KIT_LEVELS=check fails on stale files.
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { referenceById } from '../engine/autoEq';
import { makeDrumProcessor } from './engine/workletHarness';
import { generateDrumTables } from './engine/drumtables';
import { FACTORY_KIT_BASES, kitToState, type Kit } from './kits';
import { KitCapture, fitKitMix } from './kitMix';
import { pad, PAD_COUNT } from './params';

const MODE = process.env.KIT_LEVELS;
const ROOT = new URL('../../', import.meta.url).pathname;
const TS_OUT = `${ROOT}src/drum/kitLevels.gen.ts`, CPP_OUT = `${ROOT}juce/source/drum/dsp/KitLevels.gen.h`;
const SR = 48000, BLOCK = 128, PASSES = 2, AMOUNT = 0.8;
// Two passes can stack large moves; a pad stays audible and in its role.
const MAX_CUT = 9, MAX_BOOST = 6;

function decodeWav(buf: Buffer): { sampleRate: number; buf: ArrayBuffer } {
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  let at = 12, sampleRate = 0, data = new Float32Array(0);
  while (at + 8 <= dv.byteLength) {
    const id = String.fromCharCode(...buf.subarray(at, at + 4)), size = dv.getUint32(at + 4, true), body = at + 8;
    if (id === 'fmt ') sampleRate = dv.getUint32(body + 4, true);
    if (id === 'data') { data = new Float32Array(size / 2); for (let i = 0; i < data.length; i++) data[i] = dv.getInt16(body + i * 2, true) / 32768; }
    at = body + size + (size & 1);
  }
  return { sampleRate, buf: data.buffer };
}

// The one-shot bank in the order the engine sends it (sample<i>Url imports).
function oneShots() {
  const gen = readFileSync(`${ROOT}src/drum/engine/oneshots.gen.ts`, 'utf8');
  const paths = [...gen.matchAll(/import sample(\d+)Url from '([^']+)\?url'/g)].sort((a, b) => +a[1] - +b[1]).map(m => m[2]);
  return paths.map(p => decodeWav(readFileSync(new URL(p, new URL('engine/', import.meta.url)))));
}

const tables = generateDrumTables();
const tableMsg = { t: 'tables', list: tables.map((t) => ({ frames: t.frames, mips: t.mips, size: t.size, buf: t.data.slice().buffer })) };

function boot(kit: Kit, params: Record<string, number>, samples: ReturnType<typeof oneShots>) {
  const h = makeDrumProcessor(SR);
  h.send({ t: 'init', params });
  h.send(tableMsg);
  h.send({ t: 'samples', list: samples.map(s => ({ sampleRate: s.sampleRate, buf: s.buf.slice(0) })) });
  h.send({ t: 'seed', v: 1 });
  const state = kitToState(kit);
  h.send({ t: 'pats', data: state.patterns.slice().buffer });
  h.send({ t: 'chain', list: state.chain });
  h.send({ t: 'play' });
  const bar = 4 * 60 / (params['seq.bpm'] || 120) * SR / BLOCK;
  h.render(Math.ceil(bar));
  return { h, bar, state };
}

/** Plays the kit's chain after a bar of warm-up and returns each pad's mean band power. */
function learn(kit: Kit, params: Record<string, number>, samples: ReturnType<typeof oneShots>) {
  const { h, bar, state } = boot(kit, params, samples);
  const capture = new KitCapture(SR, PAD_COUNT);
  h.send({ t: 'padCapture', on: true });
  // At least four bars, so single-pattern kits average over a phrase too.
  const blocks = Math.ceil(bar * Math.max(4, state.chain.length));
  for (let done = 0; done < blocks; done += 200) {
    h.sent.length = 0;
    h.render(Math.min(200, blocks - done));
    for (const m of h.sent) if (m.t === 'padAudio') capture.add(m.pad as number, m.data as Float32Array, m.frames as number);
  }
  return capture.meanBands();
}

/** Output RMS of the kit's groove in dB, over the same window as `learn`. */
function loudness(kit: Kit, params: Record<string, number>, samples: ReturnType<typeof oneShots>) {
  const { h, bar, state } = boot(kit, params, samples);
  const { L, R } = h.render(Math.ceil(bar * Math.max(4, state.chain.length)));
  let e = 0;
  for (let i = 0; i < L.length; i++) e += 0.5 * (L[i] * L[i] + R[i] * R[i]);
  return 10 * Math.log10(e / L.length);
}

const round = (v: number) => Math.round(v * 1000) / 1000;

/** A C++ float literal: `1` → `1.0f`, `0.55` → `0.55f`. */
const cf = (v: number) => `${Number.isInteger(v) ? v.toFixed(1) : v}f`;

type Trim = { volume?: number; pads: Record<number, number> };

function render(levels: Record<string, Trim>) {
  const names = Object.keys(levels);
  const ts = `// DO NOT EDIT — generated by \`npm run kits:levels\` (src/drum/kitLevels.generate.test.ts).
// KIT MIX level trims that move every factory kit toward the PART · DRUMS
// curve: \`pad<i>.lvl\` values by pad index, and the \`master.volume\` that
// keeps the kit's output level where it was.
export const KIT_LEVELS: Record<string, { volume?: number; pads: Record<number, number> }> = {
${names.map(n => `  '${n}': { ${levels[n].volume !== undefined ? `volume: ${levels[n].volume}, ` : ''}pads: { ${Object.entries(levels[n].pads).map(([i, v]) => `${i}: ${v}`).join(', ')} } },`).join('\n')}
};
`;
  const cpp = `// DO NOT EDIT — generated by \`npm run kits:levels\` (src/drum/kitLevels.generate.test.ts).
// KIT MIX level trims for the factory kits; mirrors src/drum/kitLevels.gen.ts.
#pragma once
#include <utility>
#include <vector>

namespace fable {
// \`volume\` < 0 leaves master.volume at the kit's value.
struct KitLevelTrim { const char* kit; float volume; std::vector<std::pair<int, float>> levels; };
inline const std::vector<KitLevelTrim>& kitLevelTrims() {
    static const std::vector<KitLevelTrim> trims = {
${names.map(n => `        { "${n}", ${cf(levels[n].volume ?? -1)}, { ${Object.entries(levels[n].pads).map(([i, v]) => `{ ${i}, ${cf(v)} }`).join(', ')} } },`).join('\n')}
    };
    return trims;
}
} // namespace fable
`;
  return { ts, cpp };
}

describe.skipIf(!MODE)('factory kit levels', () => {
  it('fits every kit to the PART · DRUMS curve', () => {
    const samples = oneShots();
    const ref = referenceById('drums');
    const levels: Record<string, Trim> = {};
    const report: string[] = [];
    for (const kit of FACTORY_KIT_BASES) {
      const params = { ...kitToState(kit).params };
      const before: number[] = [];
      let first = 0, last = 0;
      for (let pass = 0; pass < PASSES; pass++) {
        const lvl = Array.from({ length: PAD_COUNT }, (_, i) => params[pad(i, 'lvl')]);
        if (!pass) before.push(...lvl);
        const fit = fitKitMix(learn(kit, params, samples), lvl, ref, AMOUNT);
        if (!fit) break;
        if (!pass) first = fit.errorBefore;
        last = fit.errorAfter;
        fit.levels.forEach((v, i) => { if (v !== null) params[pad(i, 'lvl')] = v; });
      }
      // Limit the stacked moves, then restore the kit's output level.
      before.forEach((v, i) => {
        const d = Math.max(-MAX_CUT, Math.min(MAX_BOOST, 40 * Math.log10(params[pad(i, 'lvl')] / v)));
        params[pad(i, 'lvl')] = Math.min(1, v * 10 ** (d / 40));
      });
      // The group comp and limiter are not linear, so correct twice.
      const base = kitToState(kit).params, vol0 = base['master.volume'], target = loudness(kit, base, samples);
      let volume = vol0;
      for (let k = 0; k < 2; k++) {
        params['master.volume'] = volume;
        volume = round(Math.min(1, volume * 10 ** ((target - loudness(kit, params, samples)) / 40)));
      }
      params['master.volume'] = volume;
      const left = target - loudness(kit, params, samples);
      const changed = Object.fromEntries(before.flatMap((v, i) => round(params[pad(i, 'lvl')]) !== round(v) ? [[i, round(params[pad(i, 'lvl')])]] : []));
      levels[kit.name] = { ...(volume !== round(vol0) ? { volume } : {}), pads: changed };
      // Measured, not predicted: learn the trimmed kit once more.
      const lvlNow = Array.from({ length: PAD_COUNT }, (_, i) => params[pad(i, 'lvl')]);
      last = fitKitMix(learn(kit, params, samples), lvlNow, ref, AMOUNT)?.errorBefore ?? last;
      report.push(`${kit.name}: error ${first.toFixed(1)} → ${last.toFixed(1)} dB, ${Object.keys(changed).length} pads, output ${(-left).toFixed(1)} dB (volume ${vol0} → ${volume})`);
    }
    const { ts, cpp } = render(levels);
    writeFileSync(`${ROOT}build/kit-levels-report.txt`, report.join('\n') + '\n');
    if (MODE === 'write') { writeFileSync(TS_OUT, ts); writeFileSync(CPP_OUT, cpp); }
    else {
      expect(readFileSync(TS_OUT, 'utf8')).toBe(ts);
      expect(readFileSync(CPP_OUT, 'utf8')).toBe(cpp);
    }
  }, 600_000);
});
