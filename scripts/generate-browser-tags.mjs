#!/usr/bin/env node
// Compile the preset browser tag tables into a JUCE header; never hand-copy tags.
// Run after editing a tag file: npm run tags:generate (or tags:check in CI).
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const bundled = await build({
  stdin: {
    contents: `
      export { FACTORY_PRESETS } from './src/presets';
      export * as wtTags from './src/presetTags';
      export { FACTORY_PATCHES as BASS_PATCHES } from './src/bass/patches';
      export * as bassTags from './src/bass/patchTags';
      export { FACTORY_KITS } from './src/drum/kits';
      export * as kitTags from './src/drum/kitTags';
      export { FACTORY_PATCHES as DRUM_PATCHES } from './src/drum/patches';
      export * as padTags from './src/drum/patchTags';`,
    resolveDir: process.cwd(),
  },
  bundle: true, platform: 'node', format: 'esm', write: false,
});
const m = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const q = JSON.stringify;
// One table per machine browser. Entries follow the factory order, so the native
// side can match by name and keep its own item order.
function table(id, items, roles, characters, tagsOf) {
  const rows = items.map((it) => {
    const t = tagsOf(it.name);
    return `    { ${q(it.name)}, ${q(t?.role ?? '')}, ${q((t?.tags ?? []).join(' '))} },`;
  });
  return [
    `inline constexpr Entry k${id}Entries[] = {`, ...rows, '};',
    `inline constexpr Table ${id[0].toLowerCase()}${id.slice(1)} = { ${q(roles.join(' '))}, ${q(characters.join(' '))}, k${id}Entries, ${rows.length} };`,
  ];
}

const text = [
  '// Generated by scripts/generate-browser-tags.mjs. Edit the TypeScript tag files instead:',
  '// src/presetTags.ts, src/bass/patchTags.ts, src/drum/kitTags.ts, src/drum/patchTags.ts.',
  '#pragma once',
  '#include <cstddef>',
  'namespace fable::browserTags {',
  'struct Entry { const char* name; const char* role; const char* tags; };  // tags: space separated',
  'struct Table { const char* roles; const char* characters; const Entry* entries; std::size_t count; };',
  ...table('Wt1', m.FACTORY_PRESETS, m.wtTags.PRESET_ROLES, m.wtTags.PRESET_CHARACTERS, m.wtTags.factoryPresetTags),
  ...table('Bl1', m.BASS_PATCHES, m.bassTags.PATCH_ROLES, m.bassTags.PATCH_CHARACTERS, m.bassTags.factoryPatchTags),
  ...table('DrKits', m.FACTORY_KITS, m.kitTags.KIT_ROLES, m.kitTags.KIT_CHARACTERS, m.kitTags.factoryKitTags),
  ...table('DrPads', m.DRUM_PATCHES, m.padTags.PATCH_ROLES, m.padTags.PATCH_CHARACTERS, m.padTags.factoryPatchTags),
  '} // namespace fable::browserTags', '',
].join('\n');

const path = 'juce/source/ui/BrowserTags.gen.h';
if (process.argv.includes('--check')) {
  let old = '';
  try { old = await readFile(path, 'utf8'); } catch { /* missing counts as stale */ }
  if (old !== text) throw new Error(`${path} is stale; run npm run tags:generate`);
  console.log(`Checked ${path}`);
} else {
  await writeFile(path, text);
  console.log(`Wrote ${path}`);
}
