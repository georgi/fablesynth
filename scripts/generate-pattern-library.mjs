#!/usr/bin/env node
// Writes juce/source/drum/dsp/PatternLibrary.gen.h from src/drum/patternLibrary.ts,
// the DR-1 pattern browser library (genres × song sections). Each entry's used
// bars are packed at 2 bits per step (0 rest, 1 hit, 2 accent; step order
// bar → pad → step, four steps per byte, low bits first) and base64 encoded;
// PatternLibrary.cpp decodes them at startup. `--check` fails when the header
// is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cppPath = path.join(root, 'juce/source/drum/dsp/PatternLibrary.gen.h');

// Bundle in memory so generation needs neither a dev server nor a network port.
const bundled = await build({
  stdin: { contents: 'export * from "./src/drum/patternLibrary";', resolveDir: root },
  bundle: true, platform: 'node', format: 'esm', write: false, logLevel: 'silent',
});
const { PATTERN_LIBRARY, PATTERN_USES, PATTERN_FAMILIES } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const BAR = 256;
const fail = (m) => { throw new Error(`patternLibrary.ts: ${m}`); };
const str = (s) => JSON.stringify(s);
const num = (v) => { const s = String(v); return /[.e]/.test(s) ? `${s}f` : `${s}.0f`; };

const notes = [];
const noteIndex = (n) => { let i = notes.indexOf(n); if (i < 0) { i = notes.length; notes.push(n); } return i; };

const rows = PATTERN_LIBRARY.map((e, i) => {
  const bars = e.chain.length;
  if (bars < 1 || bars > 4 || e.chain.some((v, k) => v !== k)) fail(`${e.name}: chain must be 0..n-1 with 1-4 bars`);
  if (e.patterns.length !== 4 * BAR) fail(`${e.name}: expected ${4 * BAR} pattern bytes`);
  if (e.patterns.subarray(bars * BAR).some(Boolean)) fail(`${e.name}: hits beyond the chain`);
  if (e.value !== `p${i}`) fail(`${e.name}: value ${e.value} is not p${i}`);
  if (e.tags.length !== 1 || e.tags[0] !== e.family) fail(`${e.name}: tags must be [family]`);
  const packed = Buffer.alloc(bars * BAR / 4);
  for (let k = 0; k < bars * BAR; k++) {
    const v = e.patterns[k];
    if (v > 2) fail(`${e.name}: step value ${v}`);
    packed[k >> 2] |= v << ((k & 3) * 2);
  }
  return `    { ${str(e.name)}, ${str(e.genre)}, ${str(e.role)}, ${str(e.family)}, ${e.bpm}, ${num(e.swing)}, ${noteIndex(e.note)}, ${bars}, ${str(packed.toString('base64'))} },`;
});

const out = `// DO NOT EDIT — generated by scripts/generate-pattern-library.mjs from
// src/drum/patternLibrary.ts (DR-1 pattern browser: ${PATTERN_LIBRARY.length} entries).
#pragma once

namespace fable::patternlib {
inline constexpr const char* kUses = ${str(PATTERN_USES.join(' '))};
inline constexpr const char* kFamilies = ${str(PATTERN_FAMILIES.join(' '))};
inline constexpr const char* kNotes[] = {
${notes.map((n) => `    ${str(n)},`).join('\n')}
};
// name, genre, role, family, bpm, written swing, note, bars, packed steps
struct RawEntry { const char* name; const char* genre; const char* role; const char* family; int bpm; float swing; int note; int bars; const char* packed; };
inline constexpr RawEntry kEntries[] = {
${rows.join('\n')}
};
inline constexpr int kCount = ${PATTERN_LIBRARY.length};
} // namespace fable::patternlib
`;

if (process.argv.includes('--check')) {
  const current = await readFile(cppPath, 'utf8').catch(() => '');
  if (current !== out) { console.error(`Stale ${path.relative(root, cppPath)}: run npm run patterns:generate`); process.exit(1); }
  console.log(`Checked ${path.relative(root, cppPath)} (${PATTERN_LIBRARY.length} patterns)`);
} else {
  await writeFile(cppPath, out);
  console.log(`Wrote ${path.relative(root, cppPath)} (${PATTERN_LIBRARY.length} patterns)`);
}
