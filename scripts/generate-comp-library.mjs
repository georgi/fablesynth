#!/usr/bin/env node
// Writes the WT-1 comp pattern library (src/compLibrary.ts) as native data.
// npm run comp:generate after editing the library; comp:check fails when stale.
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const out = 'juce/source/dsp/CompLibrary.gen.h';
const bundled = await build({ stdin: { contents: 'export * from "./src/compLibrary"; export * from "./src/comp";', resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', write: false });
const { COMP_LIBRARY, COMP_FAMILIES, COMP_VARIATIONS, COMP_VOICINGS, STRUM_DIRS, formatCompSteps } =
  await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const q = JSON.stringify;
const text = [
  '// Generated by scripts/generate-comp-library.mjs from src/compLibrary.ts. Do not edit.',
  '#pragma once', '#include <array>', 'namespace fable {',
  '// Steps use the comp notation of compPattern(); strumDir indexes up/down/alt,',
  '// voicing indexes close/drop2/drop24/open.',
  'struct CompLibraryEntry { const char* name; const char* family; const char* groove; const char* variation; const char* steps; double rate, gate; int strum, strumDir, voicing; };',
  `inline const std::array<const char*, ${COMP_FAMILIES.length}>& compFamilies() { static const std::array<const char*, ${COMP_FAMILIES.length}> f {{${COMP_FAMILIES.map(f => q(f.name)).join(', ')}}}; return f; }`,
  `inline const std::array<const char*, ${COMP_VARIATIONS.length}>& compVariations() { static const std::array<const char*, ${COMP_VARIATIONS.length}> v {{${COMP_VARIATIONS.map(v => q(v.name)).join(', ')}}}; return v; }`,
  `inline const std::array<CompLibraryEntry, ${COMP_LIBRARY.length}>& compLibrary() {`,
  `    static const std::array<CompLibraryEntry, ${COMP_LIBRARY.length}> list {{`,
  ...COMP_LIBRARY.map(e => `        {${[q(e.name), q(e.family), q(e.groove), q(e.variation), q(formatCompSteps(e.comp, e.ties, e.accents)),
    e.rate === 1 / 3 ? '1.0 / 3' : e.rate === 1 / 6 ? '1.0 / 6' : String(e.rate), String(e.gate), e.strum, STRUM_DIRS.indexOf(e.strumDir), COMP_VOICINGS.indexOf(e.voicing)].join(', ')}},`),
  '    }};', '    return list;', '}', '}', '',
].join('\n');
if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== text) { console.error(`${out} is stale: run npm run comp:generate`); process.exit(1); }
  console.log(`Checked ${out}`);
} else {
  await writeFile(out, text);
  console.log(`Wrote ${out} (${COMP_LIBRARY.length} patterns)`);
}
