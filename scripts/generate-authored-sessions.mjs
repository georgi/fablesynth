#!/usr/bin/env node
// Compile authored scores into JUCE-free native data; never compose here.
// Run after editing a song: npm run songs:generate (or songs:check in CI).
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

// Native DR-1, BL-1 and WT-1 now run the same OTT, COMP and COMP side-chain
// stages as the web, so sessions reach the native library unfiltered.
function nativeSession(session) {
  return session;
}

// Bundle in memory so generation needs neither a dev server nor a network port.
const bundled = await build({ stdin: { contents: 'export * from "./src/seq/sessionPresets"; export * from "./src/seq/protocol"; export * from "./src/seq/songs/grooves"; export * from "./src/seq/clipArp"; export { CHORD_QUALITIES } from "./src/chords"; export { COMP_LIBRARY, compLibraryIndex } from "./src/compLibrary"; export { withComp } from "./src/seq/songs/comping";', resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', write: false });
{
  const { AUTHORED_SESSION_PRESETS, FACTORY_SESSION_PRESETS, SESSION_GROOVES, CHORD_QUALITIES, COMP_LIBRARY, compLibraryIndex, withComp, chordTrackArp, b64ToBytes, emptyClipBytes } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
  const quote = JSON.stringify;
  const float = (value) => `${Number(value).toFixed(9)}f`;
  const text = [
    '// Generated by scripts/generate-authored-sessions.mjs. Edit src/seq/songs instead.',
    '#pragma once', '#include "SeqFactory.h"', 'namespace fable {',
    '// A chord track stored in a clip arp (src/seq/clipArp.ts chordTrackArp).',
    'inline ArpSettings sqChordTrackArp(Machine machine, bool enabled, int key, int octave, int bars, bool link, std::initializer_list<ArpChord> chords) {',
    '    ArpSettings a; a.enabled = enabled; a.chords = true;',
    '    if (machine == Machine::BL1) { a.count = 4; a.notes[0] = 36; a.notes[1] = 39; a.notes[2] = 43; a.notes[3] = 46; }',
    '    a.chordKey = key; a.chordOctave = octave; a.chordBars = bars; a.chordLink = link; a.chordCount = 0;',
    '    for (const auto& c : chords) a.chordList[(size_t)a.chordCount++] = c;',
    '    return a;',
    '}',
    '// COMP style with a library groove (src/seq/songs/comping.ts withComp).',
    'inline void sqComp(ArpSettings& a, std::array<uint8_t, 16> masks, std::array<bool, 16> ties, std::array<bool, 16> accents,',
    '                   double rate, double gate, int strum, int strumDir, int voicing) {',
    '    a.comp = true; a.compMask = masks; a.ties = ties; a.accents = accents;',
    '    a.rate = rate; a.gate = gate; a.strum = strum; a.strumDir = strumDir; a.voicing = voicing;',
    '}',
  ];
  // Chord-track arps (clipArp.ts chordTrackArp) as one call each. Anything
  // else in the arp must be the machine default, or the native copy would drift.
  const qualities = Object.keys(CHORD_QUALITIES);
  const arpLine = (ref, arp, machine) => {
    const a = arp.settings;
    const plain = { ...chordTrackArp(machine, a.chords, a.chordKey, a.chordOctave, a.chordLink), enabled: arp.enabled };
    // COMP clips carry one library groove (songs/comping.ts withComp).
    const entry = a.style === 'comp' ? COMP_LIBRARY[compLibraryIndex(a)] : null;
    const expect = entry ? withComp(plain, entry, arp.enabled) : plain;
    if (JSON.stringify(arp) !== JSON.stringify(expect)) throw new Error('Only chord-track and library comp arps are generated');
    const chords = a.chords.map((c) => `{ ${c.start}, ${c.length}, ${c.root}, ${qualities.indexOf(c.quality)}, ${c.inversion} }`).join(', ');
    const line = `            ${ref}.hasArp = true; ${ref}.arp = sqChordTrackArp(Machine::${machine}, ${arp.enabled}, ${a.chordKey}, ${a.chordOctave}, ${a.chordBars}, ${!!a.chordLink}, { ${chords} });`;
    if (!entry) return line;
    const bools = (v) => `{{ ${v.join(', ')} }}`;
    return `${line}\n            sqComp(${ref}.arp, {{ ${a.comp.join(', ')} }}, ${bools(a.ties)}, ${bools(a.accents)}, ${a.rate}, ${a.gate}, ${a.strum}, ${['up', 'down', 'alt'].indexOf(a.strumDir)}, ${['close', 'drop2', 'drop24', 'open'].indexOf(a.voicing)});`;
  };
  // One clip's C++ statements: `scene.clips[t]` replaced from the web clip.
  const clipLines = (clip, t, machine) => {
    const text = [];
    const bytes = b64ToBytes(clip.pattern), empty = emptyClipBytes(machine, clip.bars);
    text.push(`            scene.clips[${t}] = { ${quote(clip.name)}, ${clip.bars}, sqEmptyClip(Machine::${machine}, ${clip.bars}) };`);
    if (clip.arp) text.push(arpLine(`scene.clips[${t}]`, clip.arp, machine));
    // PAD automation resolves against the retained POLY settings.
    if (clip.drumRhythm) {
      text.push(`            scene.clips[${t}].hasDrumRhythm = true;`);
      clip.drumRhythm.lanes.forEach((lane, pad) => {
        if (!lane) return;
        const base = `scene.clips[${t}].drumRhythm.lanes[${pad}]`;
        text.push(`            scene.clips[${t}].drumConfiguredLanes |= (1u << ${pad});`,
          `            ${base}.enabled = ${lane.enabled}; ${base}.sourceBar = ${lane.sourceBar};`,
          `            ${base}.steps = ${lane.steps}; ${base}.rotation = ${lane.rotation};`,
          `            ${base}.mode = DrumRhythmMode::${lane.timing.mode}; ${base}.cycleBeats = ${lane.timing.cycleBeats ?? 4};`);
        if (lane.delayMs !== undefined || lane.stepDelayMs !== undefined) {
          text.push(`            ${base}.micro = true; ${base}.delayMs = ${lane.delayMs ?? 0};`);
          (lane.stepDelayMs ?? []).forEach((delay, step) => {
            if (delay) text.push(`            ${base}.stepDelayMs[${step}] = ${delay};`);
          });
        }
      });
    }
    if (clip.automation?.length) {
      text.push(`            scene.clips[${t}].hasAutomation = true;`);
      for (const lane of clip.automation) {
        const mode = { clip: 'Clip', grid: 'Grid', fit: 'Fit', pad: 'Pad' }[lane.time.mode];
        const points = lane.points.map(p => `{ ${Number(p.t)}, ${Number(p.v)}, ${Number(p.c ?? 0)}, ${!!p.hold} }`).join(', ');
        text.push(`            scene.clips[${t}].automation.push_back({ ${quote(lane.target)}, ${lane.enabled}, { AutoTime::${mode}, ${lane.time.steps ?? 16}, ${lane.time.cycleBeats ?? 4} }, { ${points} } });`);
      }
    }
    // Sparse byte assignments keep the generated artifact easy to diff.
    bytes.forEach((value, i) => {
      if (value !== empty[i]) text.push(`            scene.clips[${t}].bytes[${i}] = ${value};`);
    });
    return text;
  };
  for (const [index, preset] of AUTHORED_SESSION_PRESETS.entries()) {
    const s = nativeSession(preset.session);
    // Keep each song's clip temporaries in a separate frame even under LTO.
    text.push('#if defined(_MSC_VER)', '__declspec(noinline)',
      '#elif defined(__GNUC__)', '__attribute__((noinline))', '#endif',
      `inline SessionPreset authoredSession${index}() {`, '        SessionPreset p;',
      `        p.name = ${quote(preset.name)}; p.family = ${quote(preset.family)};`,
      `        p.variation = ${quote(preset.variation)}; p.energy = ${preset.energy};`,
      `        p.tags = { ${preset.tags.map(quote).join(', ')} };`,
      `        p.session.name = p.name; p.session.bpm = ${s.bpm}; p.session.swing = ${s.swing};`,
      `        p.session.quant = Quant::${{ '1 BAR': 'Bar', '1/4': 'Quarter', OFF: 'Off' }[s.quant]};`);
    for (const t of s.tracks) {
      const patch = t.patch;
      const params = patch.kind === 'inline' ? Object.entries(patch.data.params).sort(([a], [b]) => a.localeCompare(b)) : [];
      text.push(`        p.session.tracks.push_back({ Machine::${t.machine}, ${quote(t.name)}, 0xff${t.color.slice(1)}u, ${float(t.gain)},`,
        `            { ${patch.kind === 'factory'}, ${patch.kind === 'factory' ? patch.index : patch.base ?? 0}, {} } });`);
      // Large map initializer lists reserve temporary pairs on the stack.
      // Populate the heap-backed map directly so preset recall also works on
      // Windows host threads with a default 1 MB stack.
      if (params.length) text.push('        {',
        '            static constexpr std::pair<const char*, float> params[] {',
        ...params.map(([id, value]) => `                { ${quote(id)}, ${float(value)} },`),
        '            };',
        '            for (const auto& value : params)',
        '                p.session.tracks.back().patch.params.emplace(value.first, value.second);',
        '        }');
    }
    for (const scene of s.scenes) {
      text.push('        {', `            SceneData scene; scene.name = ${quote(scene.name)};`,
        `            scene.clips.resize(${s.tracks.length}); scene.hasClip = { ${scene.clips.map(Boolean).join(', ')} };`,
        `            scene.pass = { ${(scene.pass ?? []).join(', ')} };`);
      scene.clips.forEach((clip, t) => { if (clip) text.push(...clipLines(clip, t, s.tracks[t].machine)); });
      text.push('            p.session.scenes.push_back(std::move(scene));', '        }');
    }
    text.push('        return p;', '}');
  }
  text.push('inline std::vector<SessionPreset> authoredSessionLibrary() {',
    '    std::vector<SessionPreset> result;',
    `    result.reserve(${AUTHORED_SESSION_PRESETS.length});`,
    ...AUTHORED_SESSION_PRESETS.map((_, index) => `    result.push_back(authoredSession${index}());`));
  text.push('    return result;', '}');
  // Generated sessions with scored POLY / micro-timing (src/seq/songs/grooves.ts):
  // their drum clips replace the ones SeqFactory.cpp composes.
  // Generated sessions: their note clips carry the song's chord track.
  text.push('inline void applyChordTracks(std::vector<SessionPreset>& library) {', '    for (auto& p : library) {');
  const authored = new Set(AUTHORED_SESSION_PRESETS.map((p) => p.name));
  for (const preset of FACTORY_SESSION_PRESETS.filter((p) => !authored.has(p.name))) {
    const s = nativeSession(preset.session), lines = [];
    s.scenes.forEach((scene, index) => scene.clips.forEach((clip, t) => {
      if (clip?.arp) lines.push(arpLine(`p.session.scenes[${index}].clips[${t}]`, clip.arp, s.tracks[t].machine));
    }));
    if (lines.length) text.push(`        if (p.name == ${quote(preset.name)}) {`, ...lines, '        }');
  }
  text.push('    }', '}');
  text.push('inline void applySessionGrooves(std::vector<SessionPreset>& library) {', '    for (auto& p : library) {');
  for (const preset of FACTORY_SESSION_PRESETS.filter((p) => SESSION_GROOVES[p.name])) {
    const s = nativeSession(preset.session);
    text.push(`        if (p.name == ${quote(preset.name)}) {`);
    s.scenes.forEach((scene, index) => scene.clips.forEach((clip, t) => {
      if (!clip?.drumRhythm) return;
      text.push('        {', `            auto& scene = p.session.scenes[${index}];`, ...clipLines(clip, t, s.tracks[t].machine), '        }');
    }));
    text.push('        }');
  }
  text.push('    }', '}', '} // namespace fable', '');
  const outputs = [
    ['juce/source/seq/dsp/AuthoredSessions.gen.h', text.join('\n')],
    ['juce/test/fixtures/web-session-presets.json', JSON.stringify(FACTORY_SESSION_PRESETS.map(({ name, family, variation, energy, session }) => ({ name, family, variation, energy, session: nativeSession(session) }))) + '\n'],
  ];
  for (const [path, content] of outputs) {
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8') !== content) throw new Error(`${path} is stale; run npm run songs:generate`);
    } else await writeFile(path, content);
    console.log(`${process.argv.includes('--check') ? 'Checked' : 'Wrote'} ${path}`);
  }
}
