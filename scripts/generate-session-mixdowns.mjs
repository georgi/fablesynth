#!/usr/bin/env node
// Writes juce/source/seq/dsp/SessionMixdowns.gen.h from shared/session-mixdowns.json,
// the ASSIST / auto-EQ / auto-comp results for the factory sessions. The web
// imports the JSON directly. `--check` fails when the header is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'shared/session-mixdowns.json');
const cppPath = path.join(root, 'juce/source/seq/dsp/SessionMixdowns.gen.h');

const fail = (m) => { throw new Error(`session-mixdowns.json: ${m}`); };
const num = (v) => { if (!Number.isFinite(v)) fail(`non-finite value ${v}`); const s = String(v); return /[.e]/.test(s) ? `${s}f` : `${s}.0f`; };
const str = (s) => JSON.stringify(s);
// Static tables, copied into heap vectors: a nested initializer list keeps every
// temporary on the stack, which overflows Windows' 1 MB host threads.
const table = (name, o) => Object.keys(o).length
  ? [`            static constexpr Pair ${name}[] { ${Object.entries(o).map(([k, v]) => `{ ${str(k)}, ${num(v)} }`).join(', ')} };`,
     `std::begin(${name}), std::end(${name})`]
  : [null, ''];

const doc = JSON.parse(await readFile(sourcePath, 'utf8'));
if (doc?.v !== 1 || !Array.isArray(doc.sessions)) fail('expected { "v": 1, "sessions": [...] }');
const names = new Set();
for (const s of doc.sessions) {
  if (typeof s.name !== 'string' || names.has(s.name)) fail(`bad or duplicate name ${s.name}`);
  names.add(s.name);
  if (!(s.masterVol >= 0 && s.masterVol <= 1)) fail(`${s.name}: masterVol out of range`);
  if (!Array.isArray(s.tracks)) fail(`${s.name}: tracks must be an array`);
}

const out = `// DO NOT EDIT — generated by scripts/generate-session-mixdowns.mjs from
// shared/session-mixdowns.json (factory-session auto-EQ, auto-comp, ASSIST).
#pragma once
#include <iterator>
#include <utility>
#include <vector>

namespace fable {
struct TrackMixdown { float gain; std::vector<std::pair<const char*, float>> params; };
struct SessionMixdown {
    const char* name;
    float masterVol;
    std::vector<std::pair<const char*, float>> masterFx;
    std::vector<TrackMixdown> tracks;
};
inline const std::vector<SessionMixdown>& sessionMixdowns() {
    static const std::vector<SessionMixdown> mixdowns = [] {
        using Pair = std::pair<const char*, float>;
        std::vector<SessionMixdown> out;
        out.reserve(${doc.sessions.length});
${doc.sessions.map((s) => {
  const [masterDecl, master] = table('master', s.masterFx);
  const lines = ['        {'];
  if (masterDecl) lines.push(masterDecl);
  lines.push(`            out.push_back({ ${str(s.name)}, ${num(s.masterVol)}, { ${master} }, {} });`);
  s.tracks.forEach((t, i) => {
    const [decl, range] = table(`track${i}`, t.params);
    if (decl) lines.push(decl);
    lines.push(`            out.back().tracks.push_back({ ${num(t.gain)}, { ${range} } });`);
  });
  lines.push('        }');
  return lines.join('\n');
}).join('\n')}
        return out;
    }();
    return mixdowns;
}
} // namespace fable
`;

if (process.argv.includes('--check')) {
  const current = await readFile(cppPath, 'utf8').catch(() => '');
  if (current !== out) { console.error(`Stale ${path.relative(root, cppPath)}: run npm run mixdowns:generate`); process.exit(1); }
  console.log(`Checked ${path.relative(root, cppPath)}`);
} else {
  await writeFile(cppPath, out);
  console.log(`Wrote ${path.relative(root, cppPath)} (${doc.sessions.length} sessions)`);
}
